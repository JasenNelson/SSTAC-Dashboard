-- public.is_admin() (production prosrc md5 e0f193794d592eb6ba01424f7c5af465).
create or replace function public.is_admin()
 returns boolean
 language sql
 stable security definer
 set search_path to 'public', 'pg_temp'
as $function$
    SELECT EXISTS (
      SELECT 1 FROM public.user_roles
      WHERE user_id = auth.uid() AND role = 'admin'
    );
  $function$;
revoke all on function public.is_admin() from public, anon, authenticated, service_role;
grant execute on function public.is_admin() to authenticated, service_role;

-- user_roles policies (production pg_policies, verbatim).
create policy "Users can read own role" on public.user_roles
  as permissive for select to authenticated using ((auth.uid() = user_id));
create policy "Admins can read all roles" on public.user_roles
  as permissive for select to authenticated using (is_admin());
create policy "Admins can manage roles" on public.user_roles
  as permissive for all to authenticated using (is_admin()) with check (is_admin());
create policy "Allow system function inserts" on public.user_roles
  as permissive for insert to public with check ((auth.uid() IS NULL));

